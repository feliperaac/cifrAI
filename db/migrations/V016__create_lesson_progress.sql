CREATE TABLE LESSON_PROGRESS (
    USER_ID            RAW(16)                   NOT NULL,
    LESSON_ID          VARCHAR2(64 CHAR)         NOT NULL,
    COMPLETIONS        NUMBER(6)                 DEFAULT 0 NOT NULL,
    BEST_SCORE         NUMBER(3),
    FIRST_COMPLETED_AT TIMESTAMP WITH TIME ZONE,
    LAST_COMPLETED_AT  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_LESSON_PROGRESS PRIMARY KEY (USER_ID, LESSON_ID),
    CONSTRAINT FK_LESSON_PROGRESS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
)
