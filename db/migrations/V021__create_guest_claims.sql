CREATE TABLE GUEST_CLAIMS (
    GUEST_ID    RAW(16)                   NOT NULL,
    USER_ID     RAW(16)                   NOT NULL,
    CLAIMED_AT  TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    EVENT_COUNT NUMBER(10)                DEFAULT 0 NOT NULL,
    CONSTRAINT PK_GUEST_CLAIMS PRIMARY KEY (GUEST_ID),
    CONSTRAINT FK_GUEST_CLAIMS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
)
