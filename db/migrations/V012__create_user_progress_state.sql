CREATE TABLE USER_PROGRESS_STATE (
    USER_ID          RAW(16)                   NOT NULL,
    XP_TOTAL         NUMBER(10)                DEFAULT 0 NOT NULL,
    STREAK_CURRENT   NUMBER(5)                 DEFAULT 0 NOT NULL,
    STREAK_BEST      NUMBER(5)                 DEFAULT 0 NOT NULL,
    STREAK_LAST_DATE DATE,
    DAILY_GOAL_XP    NUMBER(5)                 DEFAULT 0 NOT NULL,
    RULES_VERSION    NUMBER(5)                 DEFAULT 1 NOT NULL,
    STATE_VERSION    NUMBER(19)                DEFAULT 0 NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT PK_USER_PROGRESS_STATE PRIMARY KEY (USER_ID),
    CONSTRAINT FK_USER_PROGRESS_STATE_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
)
