CREATE TABLE SESSIONS (
    ID                  RAW(16)                   NOT NULL,
    USER_ID             RAW(16)                   NOT NULL,
    TOKEN_HASH          RAW(32)                   NOT NULL,
    CLIENT_KIND         VARCHAR2(16 CHAR)         DEFAULT 'web' NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    LAST_SEEN_AT        TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    EXPIRES_AT          TIMESTAMP WITH TIME ZONE  NOT NULL,
    ABSOLUTE_EXPIRES_AT TIMESTAMP WITH TIME ZONE  NOT NULL,
    REVOKED_AT          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_SESSIONS PRIMARY KEY (ID),
    CONSTRAINT UQ_SESSIONS_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT CK_SESSIONS_CLIENT_KIND CHECK (CLIENT_KIND IN ('web', 'native')),
    CONSTRAINT FK_SESSIONS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
)
