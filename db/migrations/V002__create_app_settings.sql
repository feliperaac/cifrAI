CREATE TABLE APP_SETTINGS (
    SETTING_KEY VARCHAR2(100 CHAR)        NOT NULL,
    SETTING_VAL CLOB                      NOT NULL,
    UPDATED_AT  TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT PK_APP_SETTINGS PRIMARY KEY (SETTING_KEY),
    CONSTRAINT CK_APP_SETTINGS_JSON CHECK (SETTING_VAL IS JSON)
)
