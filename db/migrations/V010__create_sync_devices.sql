CREATE TABLE SYNC_DEVICES (
    USER_ID           RAW(16)                   NOT NULL,
    DEVICE_ID         RAW(16)                   NOT NULL,
    FIRST_SEEN_AT     TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    LAST_SYNC_AT      TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    LAST_EFFECTIVE_TS TIMESTAMP WITH TIME ZONE,
    LAST_CLIENT_SEQ   NUMBER(19),
    CONSTRAINT PK_SYNC_DEVICES PRIMARY KEY (USER_ID, DEVICE_ID),
    CONSTRAINT FK_SYNC_DEVICES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
)
