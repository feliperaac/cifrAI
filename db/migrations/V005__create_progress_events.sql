CREATE TABLE PROGRESS_EVENTS (
    ID              RAW(16)                   NOT NULL,
    USER_ID         RAW(16)                   NOT NULL,
    DEVICE_ID       RAW(16)                   NOT NULL,
    CLIENT_SEQ      NUMBER(19)                NOT NULL,
    EVENT_TYPE      VARCHAR2(64 CHAR)         NOT NULL,
    SCHEMA_VERSION  NUMBER(5)                 NOT NULL,
    CONTENT_VERSION VARCHAR2(32 CHAR)         NOT NULL,
    SUBJECT_KEY     VARCHAR2(64 CHAR),
    PAYLOAD         VARCHAR2(4000 CHAR)       NOT NULL,
    PAYLOAD_HASH    RAW(32)                   NOT NULL,
    CLIENT_TS       TIMESTAMP WITH TIME ZONE  NOT NULL,
    EFFECTIVE_TS    TIMESTAMP WITH TIME ZONE  NOT NULL,
    RECEIVED_AT     TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CLIENT_TZ       VARCHAR2(64 CHAR)         NOT NULL,
    LOCAL_DATE      DATE                      NOT NULL,
    LATE            NUMBER(1)                 DEFAULT 0 NOT NULL,
    GUEST_ID        RAW(16),
    SERVER_SEQ      NUMBER(19)                GENERATED ALWAYS AS IDENTITY,
    CONSTRAINT PK_PROGRESS_EVENTS PRIMARY KEY (ID),
    CONSTRAINT FK_PROGRESS_EVENTS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT UQ_PROGRESS_EVENTS_SERVER_SEQ UNIQUE (SERVER_SEQ),
    CONSTRAINT CK_PROGRESS_EVENTS_LATE CHECK (LATE IN (0, 1)),
    CONSTRAINT CK_PROGRESS_EVENTS_PAYLOAD CHECK (PAYLOAD IS JSON)
)
