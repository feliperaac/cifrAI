CREATE TABLE REVIEW_CARDS (
    USER_ID          RAW(16)                   NOT NULL,
    CARD_ID          VARCHAR2(64 CHAR)         NOT NULL,
    EASINESS         NUMBER(4,2)               NOT NULL,
    INTERVAL_DAYS    NUMBER(5)                 NOT NULL,
    REPETITIONS      NUMBER(5)                 NOT NULL,
    DUE_AT           TIMESTAMP WITH TIME ZONE  NOT NULL,
    LAST_REVIEWED_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_REVIEW_CARDS PRIMARY KEY (USER_ID, CARD_ID),
    CONSTRAINT FK_REVIEW_CARDS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
)
