CREATE TABLE USERS (
    ID            RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    EMAIL         VARCHAR2(254 CHAR)        NOT NULL,
    PASSWORD_HASH VARCHAR2(255 CHAR)        NOT NULL,
    DISPLAY_NAME  VARCHAR2(80 CHAR),
    TIMEZONE      VARCHAR2(64 CHAR)         DEFAULT 'America/Sao_Paulo' NOT NULL,
    LOCALE        VARCHAR2(10 CHAR)         DEFAULT 'pt-BR' NOT NULL,
    LEFT_HANDED   NUMBER(1)                 DEFAULT 0 NOT NULL,
    CREATED_AT    TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    UPDATED_AT    TIMESTAMP WITH TIME ZONE  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_EMAIL_LOWER CHECK (EMAIL = LOWER(EMAIL)),
    CONSTRAINT CK_USERS_LEFT_HANDED CHECK (LEFT_HANDED IN (0, 1))
)
