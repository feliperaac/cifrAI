CREATE TABLE DAILY_ACTIVITY (
    USER_ID           RAW(16)     NOT NULL,
    LOCAL_DATE        DATE        NOT NULL,
    XP                NUMBER(6)   DEFAULT 0 NOT NULL,
    LESSONS_COMPLETED NUMBER(5)   DEFAULT 0 NOT NULL,
    GOAL_XP           NUMBER(5)   DEFAULT 0 NOT NULL,
    GOAL_MET          NUMBER(1)   DEFAULT 0 NOT NULL,
    COUNTS_FOR_STREAK NUMBER(1)   DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DAILY_ACTIVITY PRIMARY KEY (USER_ID, LOCAL_DATE),
    CONSTRAINT FK_DAILY_ACTIVITY_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_DAILY_ACTIVITY_GOAL_MET CHECK (GOAL_MET IN (0, 1)),
    CONSTRAINT CK_DAILY_ACTIVITY_STREAK CHECK (COUNTS_FOR_STREAK IN (0, 1))
)
